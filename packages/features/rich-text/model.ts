/**
 * نموذج بيانات محرر النصوص الغنية (Rich-Text Editor Model)
 *
 * القرار المعماري المعتمد للتخزين:
 * التخزين الأصيل المعتمد لبيانات المستند هو HTML الدلالي النظيف (Semantic HTML).
 * - NativeEditor.getHTML() هو المصدر الأصيل والمباشر للبيانات.
 * - يتم الحفاظ على التوافق الرجعي مع كائنات TipTap JSON التراثية عبر دالة التحويل التلقائي.
 */
export interface RichTextData {
  /**
   * محتوى المحرر بصيغة HTML دلالي نظيف أو كائن متوافق.
   */
  content: string | unknown;
}

export const emptyRichTextContent = '<p><br></p>';

/**
 * استخراج المحتوى كـ HTML دلالي قياسي
 */
export function normalizeRichTextContent(content?: unknown): string {
  if (!content) return emptyRichTextContent;
  if (typeof content === 'string') return content;
  return emptyRichTextContent;
}
